-- AIRPORT DATABASE - LAB 2
-- Run this file in pgAdmin Query Tool while connected to the Airport database.
-- It creates the 10 tables and their primary/foreign-key relationships.

CREATE TABLE IF NOT EXISTS airline (
    airline_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airline_code VARCHAR(30) NOT NULL UNIQUE,
    airline_name VARCHAR(50) NOT NULL,
    airline_country VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS airport (
    airport_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airport_name VARCHAR(50) NOT NULL,
    country VARCHAR(50) NOT NULL,
    state VARCHAR(50) NOT NULL,
    city VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS passengers (
    passenger_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    date_of_birth DATE NOT NULL,
    gender VARCHAR(50) NOT NULL,
    country_of_citizenship VARCHAR(50) NOT NULL,
    country_of_residence VARCHAR(50) NOT NULL,
    passport_number VARCHAR(20) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS flights (
    flight_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sch_departure_time TIMESTAMP NOT NULL,
    sch_arrival_time TIMESTAMP NOT NULL,
    departing_airport_id INTEGER NOT NULL,
    arriving_airport_id INTEGER NOT NULL,
    departing_gate TEXT NOT NULL,
    arriving_gate VARCHAR(50) NOT NULL,
    airline_id INTEGER NOT NULL,
    act_departure_time TIMESTAMP NOT NULL,
    act_arrival_time TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_flights_departing_airport
        FOREIGN KEY (departing_airport_id) REFERENCES airport(airport_id),
    CONSTRAINT fk_flights_arriving_airport
        FOREIGN KEY (arriving_airport_id) REFERENCES airport(airport_id),
    CONSTRAINT fk_flights_airline
        FOREIGN KEY (airline_id) REFERENCES airline(airline_id)
);

CREATE TABLE IF NOT EXISTS booking (
    booking_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id INTEGER NOT NULL,
    passenger_id INTEGER NOT NULL,
    booking_platform VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(50) NOT NULL DEFAULT 'Confirmed',
    ticket_price DECIMAL(7,2) NOT NULL,
    CONSTRAINT fk_booking_flight
        FOREIGN KEY (flight_id) REFERENCES flights(flight_id),
    CONSTRAINT fk_booking_passenger
        FOREIGN KEY (passenger_id) REFERENCES passengers(passenger_id)
);

CREATE TABLE IF NOT EXISTS booking_flight (
    booking_flight_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL,
    flight_id INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_booking_flight_booking
        FOREIGN KEY (booking_id) REFERENCES booking(booking_id),
    CONSTRAINT fk_booking_flight_flight
        FOREIGN KEY (flight_id) REFERENCES flights(flight_id),
    CONSTRAINT uq_booking_flight UNIQUE (booking_id, flight_id)
);

CREATE TABLE IF NOT EXISTS baggage (
    baggage_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weight_in_kg DECIMAL(4,2) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    booking_id INTEGER NOT NULL,
    CONSTRAINT fk_baggage_booking
        FOREIGN KEY (booking_id) REFERENCES booking(booking_id)
);

CREATE TABLE IF NOT EXISTS baggage_check (
    baggage_check_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_result VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    booking_id INTEGER NOT NULL,
    passenger_id INTEGER NOT NULL,
    CONSTRAINT fk_baggage_check_booking
        FOREIGN KEY (booking_id) REFERENCES booking(booking_id),
    CONSTRAINT fk_baggage_check_passenger
        FOREIGN KEY (passenger_id) REFERENCES passengers(passenger_id)
);

CREATE TABLE IF NOT EXISTS boarding_pass (
    boarding_pass_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL,
    seat VARCHAR(50) NOT NULL,
    boarding_time TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_boarding_pass_booking
        FOREIGN KEY (booking_id) REFERENCES booking(booking_id)
);

CREATE TABLE IF NOT EXISTS security_check (
    security_check_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_result VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    passenger_id INTEGER NOT NULL,
    CONSTRAINT fk_security_check_passenger
        FOREIGN KEY (passenger_id) REFERENCES passengers(passenger_id)
);

-- Quick verification: this should return 10 table names.
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_type = 'BASE TABLE'
ORDER BY table_name;
